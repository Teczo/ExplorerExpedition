-- One hint a team may spend a token on, copied from the mission's
-- `HintDefinition` list. Handing hints out and counting tokens is EXPD-046;
-- the tokens themselves are rows in `inventory_item`.
CREATE TABLE hint (
  id                   uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organisation_id      uuid NOT NULL REFERENCES organisation (id) ON DELETE CASCADE,
  mission_instance_id  uuid NOT NULL REFERENCES mission_instance (id) ON DELETE CASCADE,
  -- The `HintDefinition.id` used inside the definition document.
  hint_key             text NOT NULL CHECK (length(btrim(hint_key)) > 0),
  text                 text NOT NULL CHECK (length(btrim(text)) > 0),
