-- EXPD-003 — PostgreSQL core data model.
--
-- The first migration. It creates every table the platform stores, plus the
-- enum types and indexes they need. Nothing here is behaviour: no triggers
-- that score, no rules that decide when a team may move on. Those belong to
-- the engine tickets (EXPD-009 to EXPD-015) and the API tickets
-- (EXPD-016 to EXPD-023).
--
-- Two ideas run through the whole file.
--
-- 1. The Expedition Definition (EXPD-002) is the contract. A published
--    expedition is stored whole, as one JSONB document, in
--    `expedition_version.definition`. That document is the source of truth,
--    and the engine can run an expedition from it alone.
--
-- 2. `mission_instance`, `mission_node` and `hint` are a flat copy of the
--    parts of that document other tables have to point at. A mission attempt
--    needs a real foreign key to the mission it is an attempt of, and a
--    string buried in a JSONB document cannot be one. EXPD-017 keeps the copy
--    in step with the document when a version is written.
--
-- Requires PostgreSQL 14 or newer. `gen_random_uuid()` has been built in
-- since 13, so no extension is installed.

BEGIN;

-- ---------------------------------------------------------------------------
-- Conventions
-- ---------------------------------------------------------------------------
--
-- Primary keys      `uuid`, generated by the database.
-- Times             `timestamptz`. The database never stores a local time.
-- Durations         whole seconds, named `*_seconds`, matching EXPD-002.
-- Points            whole numbers. EXPD-002 has no fractional scores.
-- Enum values       kebab-case, copied from the EXPD-002 union types where
--                   one exists. `subscription_status` is the one exception:
--                   it uses Stripe's own values, because that is the contract
--                   with Stripe (EXPD-068).
-- Tenancy           every table an organisation owns carries
--                   `organisation_id`, even when it could be reached through
--                   a parent. EXPD-004 and EXPD-005 filter on that column.
-- Naming            the table for a user is `app_user`. `user` is a reserved
--                   word in SQL, and `SELECT user` already means something
--                   else in PostgreSQL.

-- ---------------------------------------------------------------------------
-- Helpers
-- ---------------------------------------------------------------------------

-- Keeps `updated_at` honest. Attached below to every table that has one.
CREATE FUNCTION set_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

COMMENT ON FUNCTION set_updated_at() IS
  'Trigger function. Sets updated_at to now() on every UPDATE.';

