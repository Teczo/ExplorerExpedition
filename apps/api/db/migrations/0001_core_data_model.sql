-- ---------------------------------------------------------------------------
-- Event streams
-- ---------------------------------------------------------------------------
--
-- The three tables below are append-only. A row is written once and never
-- changed, which is why none of them has an `updated_at` column or an update
-- trigger. Making that a rule the database enforces is EXPD-014 for scores
-- and EXPD-006 for the audit log.

-- Every time a team's score moved, and why.
--
-- This is the record. `team.total_score` is a total kept alongside it for
-- speed, and can always be rebuilt by adding up a team's rows here.
CREATE TABLE score_event (
  id                     uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organisation_id        uuid NOT NULL REFERENCES organisation (id) ON DELETE CASCADE,
  expedition_session_id  uuid NOT NULL REFERENCES expedition_session (id) ON DELETE CASCADE,
  team_id                uuid NOT NULL REFERENCES team (id) ON DELETE CASCADE,
  -- Set when one member's action caused it.
  participant_id         uuid REFERENCES participant (id) ON DELETE SET NULL,
  reason                 score_event_reason NOT NULL,
  -- Positive for points earned, negative for points taken away.
  points                 integer NOT NULL,
  -- What the points were for, as much of it as is known.
  mission_instance_id    uuid REFERENCES mission_instance (id) ON DELETE SET NULL,
  mission_attempt_id     uuid REFERENCES mission_attempt (id) ON DELETE SET NULL,
  submission_id          uuid REFERENCES submission (id) ON DELETE SET NULL,
  hint_id                uuid REFERENCES hint (id) ON DELETE SET NULL,
  -- The `ScoringRule.id` from the definition document, when a rule caused
  -- this. A string, because the rule lives inside the document.
  scoring_rule_key       text,
  -- Set when a teacher adjusted the score by hand (EXPD-058).
  created_by             uuid REFERENCES app_user (id) ON DELETE SET NULL,
  -- Why, in the teacher's own words, on a manual adjustment.
  note                   text,
  metadata               jsonb NOT NULL DEFAULT '{}'::jsonb,
  occurred_at            timestamptz NOT NULL DEFAULT now(),
  created_at             timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT score_event_metadata_is_object
    CHECK (jsonb_typeof(metadata) = 'object'),
  -- A hand adjustment says who made it. Everything else is the engine.
  CONSTRAINT score_event_manual_has_author
    CHECK (reason <> 'manual-adjustment' OR created_by IS NOT NULL)
);

-- Adds up one team's score, and draws a team's own history in order.
CREATE INDEX score_event_team_id_occurred_at_idx
  ON score_event (team_id, occurred_at);
CREATE INDEX score_event_session_occurred_at_idx
  ON score_event (expedition_session_id, occurred_at);
CREATE INDEX score_event_mission_attempt_id_idx ON score_event (mission_attempt_id);

COMMENT ON TABLE score_event IS
  'Append-only record of every score change. Authoritative; team.total_score is a cache.';

-- Something that happened during a run, in the order it happened.
--
-- This is what the realtime channel sends (EXPD-023) and what Director Mode
-- replays when a teacher opens the dashboard part way through (EXPD-055).
--
-- `type` is text rather than an enum because the list of event names belongs
-- to EXPD-023 and EXPD-057, and will grow as features land. A new name must
-- not need a migration.
CREATE TABLE live_event (
  id                     uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  -- Orders events across the whole platform, and gives a client something to
  -- ask for more from after a dropped connection.
  sequence               bigint GENERATED ALWAYS AS IDENTITY,
  organisation_id        uuid NOT NULL REFERENCES organisation (id) ON DELETE CASCADE,
  expedition_session_id  uuid NOT NULL REFERENCES expedition_session (id) ON DELETE CASCADE,
  -- Set when the event is about one team, or one student, rather than the
  -- whole run.
  team_id                uuid REFERENCES team (id) ON DELETE CASCADE,
  participant_id         uuid REFERENCES participant (id) ON DELETE SET NULL,
  -- What happened, such as `team.joined` or `mission.completed`. The names
  -- are EXPD-023's to define.
  type                   text NOT NULL CHECK (length(btrim(type)) > 0),
  payload                jsonb NOT NULL DEFAULT '{}'::jsonb,
  -- Set when a teacher caused it by hand (EXPD-057).
  created_by             uuid REFERENCES app_user (id) ON DELETE SET NULL,
  occurred_at            timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT live_event_payload_is_object CHECK (jsonb_typeof(payload) = 'object')
);

CREATE UNIQUE INDEX live_event_sequence_key ON live_event (sequence);
-- Catches a client up from where it dropped.
CREATE INDEX live_event_session_sequence_idx
  ON live_event (expedition_session_id, sequence);
CREATE INDEX live_event_team_id_idx ON live_event (team_id, sequence);

COMMENT ON COLUMN live_event.type IS
  'Event name. Text rather than an enum: the vocabulary is EXPD-023 and EXPD-057.';

-- Who did what, to what, and when (EXPD-006).
--
-- The log outlives the rows it describes, so every reference out of it is
-- nullable and set to NULL rather than deleted. `entity_id` is a plain uuid
-- with no foreign key for the same reason: an entry about a deleted
-- expedition is exactly the entry somebody will want to read.
CREATE TABLE audit_log (
  id                   uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  sequence             bigint GENERATED ALWAYS AS IDENTITY,
  -- NULL on a platform-level action that belongs to no organisation.
  organisation_id      uuid REFERENCES organisation (id) ON DELETE SET NULL,
  actor_kind           audit_actor_kind NOT NULL,
  actor_user_id        uuid REFERENCES app_user (id) ON DELETE SET NULL,
  actor_participant_id uuid REFERENCES participant (id) ON DELETE SET NULL,
  -- Kept even after the account is gone, so the entry still names somebody.
  actor_label          text NOT NULL DEFAULT '',
  -- What was done, such as `expedition.published` or `submission.rejected`.
  action               text NOT NULL CHECK (length(btrim(action)) > 0),
  -- What it was done to: the table name, and the row's id.
  entity_type          text NOT NULL CHECK (length(btrim(entity_type)) > 0),
  entity_id            uuid,
  -- What changed. EXPD-006 decides how much of a row goes in here, and what
  -- has to be left out of it (EXPD-071).
  changes              jsonb NOT NULL DEFAULT '{}'::jsonb,
  -- Where the request came from.
  ip_address           inet,
  user_agent           text,
  -- Ties an entry to one API request, so a whole request reads as one story.
  request_id           text,
  occurred_at          timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT audit_log_changes_is_object
    CHECK (jsonb_typeof(changes) = 'object'),
  CONSTRAINT audit_log_user_actor_has_user
    CHECK (actor_kind <> 'user' OR actor_user_id IS NOT NULL),
  CONSTRAINT audit_log_participant_actor_has_participant
    CHECK (actor_kind <> 'participant' OR actor_participant_id IS NOT NULL)
);

CREATE UNIQUE INDEX audit_log_sequence_key ON audit_log (sequence);
CREATE INDEX audit_log_organisation_occurred_at_idx
  ON audit_log (organisation_id, occurred_at DESC);
CREATE INDEX audit_log_entity_idx ON audit_log (entity_type, entity_id, occurred_at DESC);
CREATE INDEX audit_log_actor_user_id_idx ON audit_log (actor_user_id, occurred_at DESC);
CREATE INDEX audit_log_request_id_idx ON audit_log (request_id) WHERE request_id IS NOT NULL;

COMMENT ON TABLE audit_log IS
  'Append-only. Outlives the rows it describes, so entity_id has no foreign key.';

-- ---------------------------------------------------------------------------
-- updated_at triggers
-- ---------------------------------------------------------------------------
--
-- One trigger per table that has an `updated_at` column, so that no caller
-- can forget to set it. The three append-only event tables are not listed,
-- because nothing ever updates them.

DO $$
DECLARE
  table_name text;
BEGIN
  FOREACH table_name IN ARRAY ARRAY[
    'organisation', 'app_user', 'membership', 'subscription',
    'expedition', 'expedition_version',
    'mission_type', 'mission_template',
    'mission_instance', 'mission_node', 'hint',
    'expedition_session', 'participant', 'team', 'team_member',
    'mission_attempt', 'submission',
    'media_asset', 'badge', 'ar_asset', 'qr_marker', 'inventory_item'
  ] LOOP
    EXECUTE format(
      'CREATE TRIGGER %I BEFORE UPDATE ON %I '
      'FOR EACH ROW EXECUTE FUNCTION set_updated_at()',
      table_name || '_set_updated_at',
      table_name
    );
  END LOOP;
END;
$$;

COMMIT;
