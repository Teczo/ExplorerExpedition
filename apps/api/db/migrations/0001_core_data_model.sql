-- ---------------------------------------------------------------------------
-- Running an expedition
-- ---------------------------------------------------------------------------

-- One run of one expedition with one group of students: a lesson, a school
-- trip, an open day.
--
-- A session pins the revision it runs. Publishing a new revision while a
-- session is going does not change what the students in it are playing.
--
-- `status` lists the states a run can be in. Which change may follow which,
-- and what pausing does to the clock, is EXPD-019 and EXPD-058.
CREATE TABLE expedition_session (
  id                     uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organisation_id        uuid NOT NULL REFERENCES organisation (id) ON DELETE CASCADE,
  expedition_id          uuid NOT NULL REFERENCES expedition (id) ON DELETE RESTRICT,
  -- The revision being played. RESTRICT, because a revision somebody has
  -- played must stay readable for as long as the results point at it.
  expedition_version_id  uuid NOT NULL REFERENCES expedition_version (id) ON DELETE RESTRICT,
  -- What the teacher calls this run, such as `Year 6 — Tuesday`.
  name                   text NOT NULL DEFAULT '',
  -- What students type to join (EXPD-018). Short, and not case sensitive.
  join_code              text NOT NULL CHECK (join_code ~ '^[A-Z0-9]{4,12}$'),
  status                 session_status NOT NULL DEFAULT 'scheduled',
  -- The teacher running it, and the one watching Director Mode (EXPD-055).
  host_user_id           uuid REFERENCES app_user (id) ON DELETE SET NULL,
  scheduled_start_at     timestamptz,
  started_at             timestamptz,
  -- When the current pause began. NULL while the run is not paused.
  paused_at              timestamptz,
  -- How long the run has spent paused so far, so that a team's clock can be
  -- worked out without replaying every pause (EXPD-058).
  paused_seconds_total   integer NOT NULL DEFAULT 0 CHECK (paused_seconds_total >= 0),
  ended_at               timestamptz,
  created_by             uuid REFERENCES app_user (id) ON DELETE SET NULL,
  created_at             timestamptz NOT NULL DEFAULT now(),
  updated_at             timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT expedition_session_paused_has_time
    CHECK ((status = 'paused') = (paused_at IS NOT NULL)),
  CONSTRAINT expedition_session_ended_has_time
    CHECK ((status IN ('ended', 'cancelled')) = (ended_at IS NOT NULL)),
  CONSTRAINT expedition_session_times_ordered
    CHECK (ended_at IS NULL OR started_at IS NULL OR ended_at >= started_at)
);

-- A join code only has to be unique among the runs a student could join
-- right now. Once a run ends its code goes back in the pool.
CREATE UNIQUE INDEX expedition_session_live_join_code_idx
  ON expedition_session (join_code)
  WHERE status IN ('scheduled', 'lobby', 'running', 'paused');

CREATE INDEX expedition_session_organisation_id_status_idx
  ON expedition_session (organisation_id, status);
CREATE INDEX expedition_session_expedition_id_idx ON expedition_session (expedition_id);
CREATE INDEX expedition_session_expedition_version_id_idx
  ON expedition_session (expedition_version_id);

COMMENT ON INDEX expedition_session_live_join_code_idx IS
  'Join codes are unique among joinable runs only, so codes can be reused later.';

-- One student in one run.
--
-- A participant is not an `app_user`. Most students never have an account:
-- they type a join code and a first name and start playing. `user_id` is
-- there for the case where somebody joining does have one.
--
-- There is deliberately no email, date of birth or any other contact detail
-- on this table. What may be collected about a child is EXPD-071.
CREATE TABLE participant (
  id                      uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organisation_id         uuid NOT NULL REFERENCES organisation (id) ON DELETE CASCADE,
  expedition_session_id   uuid NOT NULL REFERENCES expedition_session (id) ON DELETE CASCADE,
  -- Set only when the person joining already has an account.
  user_id                 uuid REFERENCES app_user (id) ON DELETE SET NULL,
  -- The name shown to the rest of the team. Usually a first name.
  display_name            text NOT NULL CHECK (length(btrim(display_name)) > 0),
  status                  participant_status NOT NULL DEFAULT 'joined',
  -- Identifies the phone, so that a student who closes the app can come back
  -- to the same place. Not a person, and not shared between runs.
  device_id               text,
  joined_at               timestamptz NOT NULL DEFAULT now(),
  last_seen_at            timestamptz,
  left_at                 timestamptz,
  created_at              timestamptz NOT NULL DEFAULT now(),
  updated_at              timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX participant_expedition_session_id_idx
  ON participant (expedition_session_id, status);
CREATE INDEX participant_user_id_idx ON participant (user_id);

-- One account joins one run once.
CREATE UNIQUE INDEX participant_session_user_idx
  ON participant (expedition_session_id, user_id)
  WHERE user_id IS NOT NULL;

COMMENT ON TABLE participant IS
  'A student in one run. Not an account: most students play without one.';

-- One team in one run. Teams are what score; a participant on their own
-- never does.
CREATE TABLE team (
  id                      uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organisation_id         uuid NOT NULL REFERENCES organisation (id) ON DELETE CASCADE,
  expedition_session_id   uuid NOT NULL REFERENCES expedition_session (id) ON DELETE CASCADE,
  name                    text NOT NULL CHECK (length(btrim(name)) > 0),
  status                  team_status NOT NULL DEFAULT 'forming',
  -- Where the team is in the graph. NULL until the run starts.
  current_node_id         uuid REFERENCES mission_node (id) ON DELETE SET NULL,
  -- The team's running total. `score_event` is the record of how it got
  -- there; this column is a total kept alongside it so that a leaderboard
  -- does not have to add up the stream on every read (EXPD-022).
  total_score             integer NOT NULL DEFAULT 0,
  -- Hint tokens left. EXPD-046 hands them out; the matching
  -- `inventory_item` row is the auditable record.
  hint_tokens_remaining   integer NOT NULL DEFAULT 0 CHECK (hint_tokens_remaining >= 0),
  started_at              timestamptz,
  finished_at             timestamptz,
  created_at              timestamptz NOT NULL DEFAULT now(),
  updated_at              timestamptz NOT NULL DEFAULT now(),
  UNIQUE (expedition_session_id, name),
  CONSTRAINT team_times_ordered
    CHECK (finished_at IS NULL OR started_at IS NULL OR finished_at >= started_at)
);

CREATE INDEX team_expedition_session_id_idx ON team (expedition_session_id);
CREATE INDEX team_current_node_id_idx ON team (current_node_id);
-- Draws a leaderboard for one run in one index scan.
CREATE INDEX team_leaderboard_idx
  ON team (expedition_session_id, total_score DESC, finished_at ASC);

COMMENT ON COLUMN team.total_score IS
  'Kept total. score_event is the authoritative record (EXPD-014).';

-- Which students are on which team, and what each of them is doing.
CREATE TABLE team_member (
  id               uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organisation_id  uuid NOT NULL REFERENCES organisation (id) ON DELETE CASCADE,
  team_id          uuid NOT NULL REFERENCES team (id) ON DELETE CASCADE,
  participant_id   uuid NOT NULL REFERENCES participant (id) ON DELETE CASCADE,
  -- One of the role names the expedition's `TeamRules.roles` lists, such as
  -- `navigator`. Free text, because the author chooses the names. NULL means
  -- the expedition uses no roles, or none has been handed out yet.
  role             text,
  -- The member who speaks for the team. At most one per team.
  is_leader        boolean NOT NULL DEFAULT false,
  joined_at        timestamptz NOT NULL DEFAULT now(),
  left_at          timestamptz,
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now(),
  UNIQUE (team_id, participant_id)
);

CREATE INDEX team_member_team_id_idx ON team_member (team_id);
