-- ---------------------------------------------------------------------------
-- Playing a mission
-- ---------------------------------------------------------------------------

-- One try at one mission by one team.
--
-- A team that gets a puzzle wrong twice and right on the third go has three
-- rows here. `attempt_number` counts them from one, and the mission's
-- `max_attempts` is the largest it may reach.
--
-- `status` lists the states a try can be in. The order they may be visited
-- in is the mission state machine, which is EXPD-010.
CREATE TABLE mission_attempt (
  id                      uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organisation_id         uuid NOT NULL REFERENCES organisation (id) ON DELETE CASCADE,
  expedition_session_id   uuid NOT NULL REFERENCES expedition_session (id) ON DELETE CASCADE,
  team_id                 uuid NOT NULL REFERENCES team (id) ON DELETE CASCADE,
  -- RESTRICT: a mission that has been attempted cannot be deleted out from
  -- under the attempt. This also stops a played revision being removed.
  mission_instance_id     uuid NOT NULL REFERENCES mission_instance (id) ON DELETE RESTRICT,
  -- Who opened it. NULL when the team opened it together, or is unknown.
  opened_by               uuid REFERENCES participant (id) ON DELETE SET NULL,
  attempt_number          integer NOT NULL CHECK (attempt_number > 0),
  status                  attempt_status NOT NULL DEFAULT 'open',
  started_at              timestamptz NOT NULL DEFAULT now(),
  -- When the mission's own time limit runs out. NULL when it is untimed.
  deadline_at             timestamptz,
  completed_at            timestamptz,
  -- What this try was finally worth, once scoring has run. NULL until then.
  -- The `score_event` rows are the record of how it adds up.
  awarded_points          integer,
  created_at              timestamptz NOT NULL DEFAULT now(),
  updated_at              timestamptz NOT NULL DEFAULT now(),
  UNIQUE (team_id, mission_instance_id, attempt_number),
  CONSTRAINT mission_attempt_completed_after_start
    CHECK (completed_at IS NULL OR completed_at >= started_at),
  CONSTRAINT mission_attempt_deadline_after_start
    CHECK (deadline_at IS NULL OR deadline_at > started_at),
  -- A try that is still going has not been settled.
  CONSTRAINT mission_attempt_settled_has_completed_at CHECK (
    status IN ('open', 'submitted', 'awaiting-review')
    = (completed_at IS NULL)
  )
);

CREATE INDEX mission_attempt_team_id_idx ON mission_attempt (team_id, status);
CREATE INDEX mission_attempt_mission_instance_id_idx
  ON mission_attempt (mission_instance_id);
CREATE INDEX mission_attempt_session_status_idx
  ON mission_attempt (expedition_session_id, status);
-- Finds the tries a teacher still has to look at (EXPD-056).
CREATE INDEX mission_attempt_awaiting_review_idx
  ON mission_attempt (expedition_session_id, started_at)
  WHERE status = 'awaiting-review';

-- What a team handed in for one try.
--
-- A try normally has one submission. It can have more than one when the
-- mission lets a team add to its answer, or when a queued offline submission
-- arrives after the team has already sent something (EXPD-048).
CREATE TABLE submission (
  id                  uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organisation_id     uuid NOT NULL REFERENCES organisation (id) ON DELETE CASCADE,
  mission_attempt_id  uuid NOT NULL REFERENCES mission_attempt (id) ON DELETE CASCADE,
  -- Who pressed send. NULL when it is not known which member did.
  participant_id      uuid REFERENCES participant (id) ON DELETE SET NULL,
  -- The answer itself, in whatever shape the mission type asks for: a scanned
  -- code, a typed answer, the ids of the photos taken. Checked against the
  -- type's `submission_schema` by EXPD-011.
  payload             jsonb NOT NULL DEFAULT '{}'::jsonb,
  status              submission_status NOT NULL DEFAULT 'pending',
  -- Handed in after the expedition's time limit. What that costs is the late
  -- policy in the expedition's rules.
  is_late             boolean NOT NULL DEFAULT false,
  -- When the student's device recorded it, which is not when the server got
  -- it if the phone had no signal (EXPD-048).
  submitted_at        timestamptz NOT NULL DEFAULT now(),
  received_at         timestamptz NOT NULL DEFAULT now(),
  reviewed_at         timestamptz,
  reviewed_by         uuid REFERENCES app_user (id) ON DELETE SET NULL,
  review_note         text,
  created_at          timestamptz NOT NULL DEFAULT now(),
  updated_at          timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT submission_payload_is_object
    CHECK (jsonb_typeof(payload) = 'object'),
  CONSTRAINT submission_reviewed_has_decision
    CHECK ((status IN ('accepted', 'rejected')) OR reviewed_at IS NULL)
);

CREATE INDEX submission_mission_attempt_id_idx ON submission (mission_attempt_id);
CREATE INDEX submission_participant_id_idx ON submission (participant_id);
-- The review queue for one organisation, oldest first (EXPD-056).
CREATE INDEX submission_review_queue_idx
  ON submission (organisation_id, submitted_at)
  WHERE status IN ('pending', 'needs-review');

COMMENT ON COLUMN submission.payload IS
  'The answer, in the shape the mission type defines. Checked by EXPD-011.';

-- ---------------------------------------------------------------------------
-- Media
-- ---------------------------------------------------------------------------

-- One file in Azure Blob Storage: a cover image, a mission photo, a piece of
-- evidence a team handed in.
--
-- The row never holds a URL. A URL is signed when it is asked for (EXPD-021)
-- and would go stale if it were written down here.
--
-- A row is written before the file exists, because the student's phone
-- uploads straight to the signed URL. `status` says whether the file has
-- actually arrived.
CREATE TABLE media_asset (
  id                 uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organisation_id    uuid NOT NULL REFERENCES organisation (id) ON DELETE CASCADE,
  kind               media_kind NOT NULL,
  status             media_status NOT NULL DEFAULT 'pending',
  -- Where the bytes are. Container and path together, never a URL.
  storage_container  text NOT NULL CHECK (length(btrim(storage_container)) > 0),
  storage_path       text NOT NULL CHECK (length(btrim(storage_path)) > 0),
  content_type       text,
  byte_size          bigint CHECK (byte_size IS NULL OR byte_size >= 0),
  -- Set on images and video, so that a layout can leave the right gap before
  -- the file has loaded.
  width_px           integer CHECK (width_px IS NULL OR width_px > 0),
  height_px          integer CHECK (height_px IS NULL OR height_px > 0),
  duration_seconds   integer CHECK (duration_seconds IS NULL OR duration_seconds >= 0),
  checksum_sha256    text CHECK (checksum_sha256 IS NULL OR checksum_sha256 ~ '^[a-f0-9]{64}$'),
  -- Read aloud by a screen reader in place of the file.
  alt_text           text,
  -- Set on a file in an expedition's own library (EXPD-030).
  expedition_id      uuid REFERENCES expedition (id) ON DELETE SET NULL,
  -- Set on evidence a team handed in. SET NULL rather than CASCADE, because
  -- the blob outlives the row and still has to be tidied up afterwards.
  submission_id      uuid REFERENCES submission (id) ON DELETE SET NULL,
  uploaded_by        uuid REFERENCES app_user (id) ON DELETE SET NULL,
  -- Set on evidence, where the uploader is a student and not an account.
  uploaded_by_participant uuid REFERENCES participant (id) ON DELETE SET NULL,
  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now(),
  UNIQUE (storage_container, storage_path)
);

CREATE INDEX media_asset_organisation_id_idx ON media_asset (organisation_id, kind);
CREATE INDEX media_asset_expedition_id_idx ON media_asset (expedition_id);
CREATE INDEX media_asset_submission_id_idx ON media_asset (submission_id);
-- Finds rows whose upload never finished, so they can be cleared out.
CREATE INDEX media_asset_pending_idx
  ON media_asset (created_at)
  WHERE status = 'pending';

