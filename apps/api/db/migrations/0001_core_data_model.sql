-- ---------------------------------------------------------------------------
-- Organisation, user, membership, subscription
-- ---------------------------------------------------------------------------

-- A school, a trust or a company. The tenant boundary. Nothing an
-- organisation owns is ever visible to another one (EXPD-004, EXPD-005).
CREATE TABLE organisation (
  id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name         text NOT NULL CHECK (length(btrim(name)) > 0),
  -- Used in URLs and join links. Compared without case.
  slug         text NOT NULL CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  status       organisation_status NOT NULL DEFAULT 'active',
  -- The timezone the organisation works in, as an IANA name such as
  -- `Europe/London`. Used to show a teacher a start time in their own day.
  -- Stored times stay in UTC.
  timezone     text NOT NULL DEFAULT 'UTC',
  -- Default language for the organisation's own screens, as a BCP 47 tag.
  locale       text NOT NULL DEFAULT 'en-GB',
  settings     jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX organisation_slug_key ON organisation (lower(slug));

COMMENT ON TABLE organisation IS
  'A tenant. Every other organisation-owned row carries its id.';

-- One person's account. A user is not tied to one organisation: the same
-- teacher may work for two schools, which is what `membership` is for.
--
-- There is no password or token column here on purpose. How a person proves
-- who they are is EXPD-004.
CREATE TABLE app_user (
  id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  email         text NOT NULL CHECK (position('@' IN email) > 1),
  display_name  text NOT NULL CHECK (length(btrim(display_name)) > 0),
  status        user_status NOT NULL DEFAULT 'invited',
  locale        text NOT NULL DEFAULT 'en-GB',
  last_seen_at  timestamptz,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX app_user_email_key ON app_user (lower(email));

COMMENT ON TABLE app_user IS
  'A person with an account. Named app_user because user is a reserved word.';

-- What one person may do inside one organisation. A person with accounts in
-- two organisations has two rows here and one row in `app_user`.
CREATE TABLE membership (
  id               uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organisation_id  uuid NOT NULL REFERENCES organisation (id) ON DELETE CASCADE,
  user_id          uuid NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
  role             membership_role NOT NULL DEFAULT 'member',
  status           membership_status NOT NULL DEFAULT 'invited',
  invited_by       uuid REFERENCES app_user (id) ON DELETE SET NULL,
  invited_at       timestamptz,
  accepted_at      timestamptz,
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now(),
  UNIQUE (organisation_id, user_id)
);

CREATE INDEX membership_user_id_idx ON membership (user_id);

-- Every organisation keeps at least one owner, so that nobody is ever locked
-- out of their own data.
CREATE UNIQUE INDEX membership_single_owner_idx
  ON membership (organisation_id)
  WHERE role = 'owner' AND status = 'active';

COMMENT ON INDEX membership_single_owner_idx IS
  'One active owner per organisation. Transferring ownership swaps the role in one statement.';

-- What an organisation is paying for. Seat and participant limits are read
-- from here; enforcing them is EXPD-069, and talking to Stripe is EXPD-068.
--
-- An organisation may have more than one row over time. The row that counts
-- is the one whose status is `trialing` or `active`.
CREATE TABLE subscription (
  id                      uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organisation_id         uuid NOT NULL REFERENCES organisation (id) ON DELETE CASCADE,
  -- The plan's own key, such as `school-annual`. The price lives in Stripe.
  plan_key                text NOT NULL CHECK (length(btrim(plan_key)) > 0),
  status                  subscription_status NOT NULL,
  stripe_customer_id      text,
  stripe_subscription_id  text,
  stripe_price_id         text,
  -- How many staff accounts the plan allows. NULL means no limit.
  seat_limit              integer CHECK (seat_limit IS NULL OR seat_limit > 0),
  -- How many students may play at once across the organisation's running
  -- sessions. NULL means no limit.
  participant_limit       integer CHECK (participant_limit IS NULL OR participant_limit > 0),
  -- How many expeditions may be held in `published` status. NULL means no limit.
  expedition_limit        integer CHECK (expedition_limit IS NULL OR expedition_limit > 0),
  trial_ends_at           timestamptz,
  current_period_start    timestamptz,
  current_period_end      timestamptz,
  cancel_at               timestamptz,
  cancelled_at            timestamptz,
  created_at              timestamptz NOT NULL DEFAULT now(),
  updated_at              timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT subscription_period_ordered CHECK (
    current_period_start IS NULL
    OR current_period_end IS NULL
    OR current_period_end > current_period_start
  )
);

CREATE UNIQUE INDEX subscription_stripe_subscription_id_key
  ON subscription (stripe_subscription_id)
  WHERE stripe_subscription_id IS NOT NULL;

CREATE INDEX subscription_organisation_id_idx ON subscription (organisation_id);

-- An organisation pays for one thing at a time. Older rows stay as history.
CREATE UNIQUE INDEX subscription_one_live_per_organisation_idx
  ON subscription (organisation_id)
  WHERE status IN ('trialing', 'active', 'past_due');

-- ---------------------------------------------------------------------------
-- Expeditions and their revisions
-- ---------------------------------------------------------------------------

-- One expedition, across every revision of it. The row holds the things that
-- do not change when an author publishes again: who owns it, who made it,
-- and whether it is still in use.
--
-- Everything an author can edit lives on `expedition_version`.
CREATE TABLE expedition (
  id                uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organisation_id   uuid NOT NULL REFERENCES organisation (id) ON DELETE CASCADE,
  status            expedition_status NOT NULL DEFAULT 'draft',
  source            authoring_source NOT NULL DEFAULT 'studio',
  created_by        uuid REFERENCES app_user (id) ON DELETE SET NULL,
  updated_by        uuid REFERENCES app_user (id) ON DELETE SET NULL,
  archived_at       timestamptz,
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT expedition_archived_has_date
    CHECK ((status = 'archived') = (archived_at IS NOT NULL))
);

CREATE INDEX expedition_organisation_id_status_idx
  ON expedition (organisation_id, status);

COMMENT ON TABLE expedition IS
  'One expedition across every revision. The editable part is expedition_version.';

-- One revision of one expedition.
--
-- `definition` holds the whole EXPD-002 Expedition Definition document. It is
-- the source of truth. The mission and node tables below are a flat copy of
-- the parts other rows have to point at, written from this document by
-- EXPD-017 whenever the revision is saved.
--
-- A published revision is never edited. Publishing again writes a new row
-- with the next `definition_version`.
CREATE TABLE expedition_version (
  id                  uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organisation_id     uuid NOT NULL REFERENCES organisation (id) ON DELETE CASCADE,
  expedition_id       uuid NOT NULL REFERENCES expedition (id) ON DELETE CASCADE,
  -- Counts from one, and goes up by one on each publish. EXPD-017 owns it.
  definition_version  integer NOT NULL CHECK (definition_version > 0),
  -- The EXPD-002 schema version the document was written against, such as
  -- `1.0.0`. A reader checks this before reading the document.
  schema_version      text NOT NULL CHECK (schema_version ~ '^\d+\.\d+\.\d+$'),
  status              expedition_status NOT NULL DEFAULT 'draft',
  -- The whole Expedition Definition. Given this and the mission type
  -- registry, the engine can run the expedition without another query.
  definition          jsonb NOT NULL,
  -- Copied out of `definition.metadata` so that a list of expeditions can be
  -- drawn without opening every document. EXPD-017 writes both together.
  title               text NOT NULL CHECK (length(btrim(title)) > 0),
  summary             text NOT NULL DEFAULT '',
  locale              text NOT NULL DEFAULT 'en-GB',
  published_at        timestamptz,
  published_by        uuid REFERENCES app_user (id) ON DELETE SET NULL,
  created_by          uuid REFERENCES app_user (id) ON DELETE SET NULL,
  created_at          timestamptz NOT NULL DEFAULT now(),
  updated_at          timestamptz NOT NULL DEFAULT now(),
  UNIQUE (expedition_id, definition_version),
  CONSTRAINT expedition_version_definition_is_object
    CHECK (jsonb_typeof(definition) = 'object'),
  -- A draft has not been published, and a published revision has a date.
  CONSTRAINT expedition_version_published_has_date
    CHECK ((status = 'published') = (published_at IS NOT NULL))
);

CREATE INDEX expedition_version_expedition_id_idx
  ON expedition_version (expedition_id, definition_version DESC);

CREATE INDEX expedition_version_organisation_id_idx
  ON expedition_version (organisation_id);

COMMENT ON COLUMN expedition_version.definition IS
  'The whole EXPD-002 Expedition Definition. Source of truth for this revision.';

-- ---------------------------------------------------------------------------
-- Mission types and templates
-- ---------------------------------------------------------------------------

-- One kind of task: scan a QR code, take a photo, solve a puzzle. The
-- registry (EXPD-009) reads these rows; this table only stores them.
--
-- A row with no `organisation_id` is a platform type every organisation can
-- use. A row with one is a type that organisation built in the Studio.
--
-- A type is never edited once published. A change means a new row with the
-- next `version`, so that an expedition pinned to the old one keeps working.
CREATE TABLE mission_type (
  id                 uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organisation_id    uuid REFERENCES organisation (id) ON DELETE CASCADE,
  -- The key an expedition pins to, such as `qr-hunt`.
  type_key           text NOT NULL CHECK (type_key ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  -- The version an expedition pins to, as three dot-separated numbers.
  version            text NOT NULL CHECK (version ~ '^\d+\.\d+\.\d+$'),
  name               text NOT NULL CHECK (length(btrim(name)) > 0),
  description        text NOT NULL DEFAULT '',
  status             mission_type_status NOT NULL DEFAULT 'draft',
  -- JSON Schema for `mission_instance.config`. Only the mission type knows
  -- the right shape for that object, so the check lives here (EXPD-009).
  config_schema      jsonb NOT NULL DEFAULT '{}'::jsonb,
  -- JSON Schema for `submission.payload`.
  submission_schema  jsonb NOT NULL DEFAULT '{}'::jsonb,
  -- What a new mission of this type starts out with in the Studio.
  default_config     jsonb NOT NULL DEFAULT '{}'::jsonb,
  -- What the type needs from the student's device: `camera`, `location`,
  -- `qr`, `ar`, `microphone`. EXPD-009 gives the list its meaning.
  capabilities       text[] NOT NULL DEFAULT '{}',
  created_by         uuid REFERENCES app_user (id) ON DELETE SET NULL,
  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT mission_type_config_schema_is_object
    CHECK (jsonb_typeof(config_schema) = 'object'),
  CONSTRAINT mission_type_submission_schema_is_object
    CHECK (jsonb_typeof(submission_schema) = 'object'),
  CONSTRAINT mission_type_default_config_is_object
    CHECK (jsonb_typeof(default_config) = 'object')
);

-- A key and version are unique within an organisation, and unique again
-- across the platform types. Two indexes, because NULL is not equal to NULL.
CREATE UNIQUE INDEX mission_type_platform_key
  ON mission_type (type_key, version)
  WHERE organisation_id IS NULL;

CREATE UNIQUE INDEX mission_type_organisation_key
  ON mission_type (organisation_id, type_key, version)
  WHERE organisation_id IS NOT NULL;

COMMENT ON COLUMN mission_type.organisation_id IS
  'NULL means a platform type available to every organisation.';

-- A mission somebody already set up, ready to drop into an expedition. The
-- template set is EXPD-060 and EXPD-061; this table is where they go.
CREATE TABLE mission_template (
  id               uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organisation_id  uuid REFERENCES organisation (id) ON DELETE CASCADE,
  mission_type_id  uuid NOT NULL REFERENCES mission_type (id) ON DELETE RESTRICT,
  name             text NOT NULL CHECK (length(btrim(name)) > 0),
  description      text NOT NULL DEFAULT '',
  status           mission_template_status NOT NULL DEFAULT 'draft',
  -- The configured settings, in the shape the mission type asks for. Copied
  -- into `mission_instance.config` when the template is used.
  config           jsonb NOT NULL DEFAULT '{}'::jsonb,
  -- The EXPD-002 `MissionScoring` object the template suggests.
  scoring          jsonb NOT NULL DEFAULT '{}'::jsonb,
  subjects         text[] NOT NULL DEFAULT '{}',
  tags             text[] NOT NULL DEFAULT '{}',
  age_min          integer CHECK (age_min IS NULL OR age_min >= 0),
  age_max          integer CHECK (age_max IS NULL OR age_max >= 0),
  created_by       uuid REFERENCES app_user (id) ON DELETE SET NULL,
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT mission_template_config_is_object
    CHECK (jsonb_typeof(config) = 'object'),
  CONSTRAINT mission_template_scoring_is_object
    CHECK (jsonb_typeof(scoring) = 'object'),
  CONSTRAINT mission_template_age_range_ordered
    CHECK (age_min IS NULL OR age_max IS NULL OR age_max >= age_min)
);

CREATE INDEX mission_template_organisation_id_idx ON mission_template (organisation_id);
CREATE INDEX mission_template_mission_type_id_idx ON mission_template (mission_type_id);
CREATE INDEX mission_template_tags_idx ON mission_template USING gin (tags);

COMMENT ON COLUMN mission_template.organisation_id IS
  'NULL means a platform template available to every organisation.';

-- ---------------------------------------------------------------------------
-- The contents of one revision: missions, nodes, hints
-- ---------------------------------------------------------------------------
--
-- These three tables are a flat copy of parts of
-- `expedition_version.definition`. They exist for two reasons, and for no
-- other: so that a runtime row can hold a real foreign key to the mission it
-- is about, and so that a query can find a mission without opening a JSONB
-- document. EXPD-017 writes them whenever it writes a version.
--
-- Each row keeps the id it has inside the document, in a `*_key` column. The
-- document's ids are strings and are only unique within one revision, so the
-- database gives every row its own uuid on top.

-- One mission placed in one revision of one expedition.
CREATE TABLE mission_instance (
  id                        uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organisation_id           uuid NOT NULL REFERENCES organisation (id) ON DELETE CASCADE,
  expedition_version_id     uuid NOT NULL REFERENCES expedition_version (id) ON DELETE CASCADE,
  -- The `MissionInstance.id` used inside the definition document.
  instance_key              text NOT NULL CHECK (length(btrim(instance_key)) > 0),

  -- What the document says the mission type is. These two are the record:
  -- they are copied straight from the document and never rewritten, so that
  -- a revision keeps pointing at the type version its author configured.
  mission_type_key          text NOT NULL,
  mission_type_version      text NOT NULL,
  -- The registry row those two resolve to, when the type is known here. A
  -- draft may name a type nobody has registered yet, so it may be NULL.
  mission_type_id           uuid REFERENCES mission_type (id) ON DELETE SET NULL,

  title                     text NOT NULL CHECK (length(btrim(title)) > 0),
  brief                     text NOT NULL DEFAULT '',
  instructions              text,

  -- The settings that belong to the mission type itself. A QR hunt keeps its
  -- codes in here, a puzzle keeps its answers. Deliberately opaque: only the
  -- mission type knows the right shape, so only EXPD-009 can check it.
  config                    jsonb NOT NULL DEFAULT '{}'::jsonb,
  -- The EXPD-002 `MissionScoring` object: base points, partial credit, cap.
  scoring                   jsonb NOT NULL DEFAULT '{}'::jsonb,
  -- Images, audio and video shown with the mission, as EXPD-002 `MediaRef`
  -- objects. Kept as an array because the document keeps their order.
  media                     jsonb NOT NULL DEFAULT '[]'::jsonb,

  -- EXPD-002 `AttemptPolicy`. NULL max means there is no limit.
  max_attempts              integer CHECK (max_attempts IS NULL OR max_attempts > 0),
  cooldown_seconds          integer NOT NULL DEFAULT 0 CHECK (cooldown_seconds >= 0),
  -- How long a team has once it opens the mission. NULL means it is untimed.
  time_limit_seconds        integer CHECK (time_limit_seconds IS NULL OR time_limit_seconds > 0),
  verification              verification_mode NOT NULL DEFAULT 'automatic',

  -- EXPD-002 `LocationConstraint`, spread into columns so that a query can
  -- ask where a mission is. All four are set together or none of them are.
  location_latitude         double precision
    CHECK (location_latitude IS NULL OR location_latitude BETWEEN -90 AND 90),
  location_longitude        double precision
    CHECK (location_longitude IS NULL OR location_longitude BETWEEN -180 AND 180),
  location_radius_metres    double precision
    CHECK (location_radius_metres IS NULL OR location_radius_metres > 0),
  location_on_poor_accuracy poor_accuracy_action,

  created_at                timestamptz NOT NULL DEFAULT now(),
  updated_at                timestamptz NOT NULL DEFAULT now(),

  UNIQUE (expedition_version_id, instance_key),
  CONSTRAINT mission_instance_config_is_object
    CHECK (jsonb_typeof(config) = 'object'),
  CONSTRAINT mission_instance_scoring_is_object
    CHECK (jsonb_typeof(scoring) = 'object'),
  CONSTRAINT mission_instance_media_is_array
    CHECK (jsonb_typeof(media) = 'array'),
  CONSTRAINT mission_instance_type_version_is_semver
    CHECK (mission_type_version ~ '^\d+\.\d+\.\d+$'),
  -- A location is given in full or not at all.
  CONSTRAINT mission_instance_location_all_or_nothing CHECK (
    num_nonnulls(
      location_latitude, location_longitude,
      location_radius_metres, location_on_poor_accuracy
    ) IN (0, 4)
  )
);

CREATE INDEX mission_instance_expedition_version_id_idx
  ON mission_instance (expedition_version_id);
CREATE INDEX mission_instance_mission_type_id_idx
  ON mission_instance (mission_type_id);
CREATE INDEX mission_instance_organisation_id_idx
  ON mission_instance (organisation_id);

COMMENT ON COLUMN mission_instance.config IS
  'Mission-type-specific settings. Shape owned by the mission type (EXPD-009).';

-- One stop in the expedition graph.
--
-- The edges between stops are not a table. They stay in
-- `expedition_version.definition`, where the engine already reads them, and a
-- copy of the ones leaving this stop is kept in `outgoing_edges` so that the
-- Studio can draw a node without loading the whole document. Nothing at
-- runtime points at an edge, which is why nothing needs one to have a key.
CREATE TABLE mission_node (
  id                     uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organisation_id        uuid NOT NULL REFERENCES organisation (id) ON DELETE CASCADE,
  expedition_version_id  uuid NOT NULL REFERENCES expedition_version (id) ON DELETE CASCADE,
  -- The `ExpeditionNode.id` used inside the definition document.
  node_key               text NOT NULL CHECK (length(btrim(node_key)) > 0),
  kind                   expedition_node_kind NOT NULL,
  -- A name for the author. Students never see it.
  title                  text NOT NULL DEFAULT '',
  notes                  text,
  -- Set when, and only when, the node holds a mission.
  mission_instance_id    uuid REFERENCES mission_instance (id) ON DELETE CASCADE,
  -- Shown to a team that reaches a finish node. NULL on every other kind.
  finish_message         text,
  -- Where the node sits on the Studio canvas (EXPD-026). No effect on play.
  layout_x               double precision,
  layout_y               double precision,
  -- The EXPD-002 `ExpeditionEdge` objects that leave this node, conditions
  -- included. A copy; the definition document is the source of truth.
  outgoing_edges         jsonb NOT NULL DEFAULT '[]'::jsonb,
  created_at             timestamptz NOT NULL DEFAULT now(),
  updated_at             timestamptz NOT NULL DEFAULT now(),

  UNIQUE (expedition_version_id, node_key),
  CONSTRAINT mission_node_edges_is_array
    CHECK (jsonb_typeof(outgoing_edges) = 'array'),
  CONSTRAINT mission_node_mission_kind_has_mission
    CHECK ((kind = 'mission') = (mission_instance_id IS NOT NULL)),
  CONSTRAINT mission_node_finish_message_only_on_finish
    CHECK (finish_message IS NULL OR kind = 'finish'),
  -- A finish node has nowhere to go, so it never carries an edge.
  CONSTRAINT mission_node_finish_has_no_edges
    CHECK (kind <> 'finish' OR outgoing_edges = '[]'::jsonb)
);

CREATE INDEX mission_node_expedition_version_id_idx
  ON mission_node (expedition_version_id);
